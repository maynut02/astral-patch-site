import { publicDataId, PUBLIC_TRANSLATION_ORIGIN } from './sync-public-translations.mjs'
import { emptyGlossaryMetadata } from '../shared/utils/glossary.ts'

export const BASE_GLOSSARY_ID = '82699bf0-3c4e-4126-b667-6ccf6f31409a'
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i

export function renderBaseGlossarySql(data) {
  if (data?.origin !== PUBLIC_TRANSLATION_ORIGIN || !Array.isArray(data.terms) || data.terms.length > 200) throw new Error('기초 용어 데이터가 올바르지 않습니다.')
  const terms = data.terms.map((term) => {
    if (!term || !UUID.test(term.sourceVersionId) || !['key', 'translation', 'japanese', 'chineseSimplified', 'chineseTraditional', 'note'].every(field => typeof term[field] === 'string' && !term[field].includes('\0'))
      || !term.key.trim() || !term.translation.trim() || !term.note.trim() || term.key.length > 1000 || term.note.length > 1000
      || ['translation', 'japanese', 'chineseSimplified', 'chineseTraditional'].some(field => Array.from(term[field]).length > 200)
      || ![term.japanese, term.chineseSimplified, term.chineseTraditional].some(Boolean)) throw new Error('기초 용어의 표기·근거 형식이 올바르지 않습니다.')
    return { ...term, id: publicDataId('base-glossary:' + term.key + ':' + term.translation) }
  })
  if (new Set(terms.map(term => term.id)).size !== terms.length) throw new Error('기초 용어가 중복되었습니다.')
  const payload = '[\n' + terms.map(term => '  ' + JSON.stringify(term)).join(',\n') + '\n]'
  if (payload.includes('$glossary_seed_json$')) throw new Error('지원하지 않는 용어 구분자가 있습니다.')
  return `-- Generated by pnpm glossary:generate from data/glossary-base.json.
-- Reviewed baseline only: validate against the deployment DB; never modify translations.
DO $base_glossary$
DECLARE
  seeds constant jsonb := $glossary_seed_json$
${payload}
$glossary_seed_json$::jsonb;
  defaults constant jsonb := '${JSON.stringify(emptyGlossaryMetadata())}'::jsonb;
  candidate jsonb;
  target_dictionary uuid;
  valid_source boolean;
  added_count integer := 0;
  existing_count integer := 0;
  skipped_keys jsonb := '[]'::jsonb;
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  PERFORM pg_advisory_xact_lock(hashtextextended('astral-base-glossary', 0));
  -- 검토 처리 순서와 같은 순서로 잠그고 일반 조회는 허용한다.
  LOCK TABLE editor_dictionary_proposals, editor_dictionary_entries, editor_dictionaries IN EXCLUSIVE MODE;
  SELECT id INTO target_dictionary FROM editor_dictionaries
    WHERE is_team AND visibility = 'public'
    ORDER BY (id = '${BASE_GLOSSARY_ID}'::uuid) DESC, created_at, id LIMIT 1;
  FOR candidate IN SELECT value FROM jsonb_array_elements(seeds) LOOP
    valid_source := false;
    SELECT true INTO valid_source
    FROM translation_units unit
    JOIN source_versions source ON source.id = unit.current_source_version_id
    JOIN translations approved ON approved.unit_id = unit.id AND approved.locale = 'ko'
    WHERE unit.namespace || '_' || unit.unit_key = candidate->>'key'
      AND source.id = (candidate->>'sourceVersionId')::uuid
      AND approved.approved_source_version_id = source.id
      AND strpos(normalize(approved.text, NFC), normalize(candidate->>'translation', NFC)) > 0
      AND (candidate->>'japanese' = '' OR strpos(normalize(source.jp, NFC), normalize(candidate->>'japanese', NFC)) > 0)
      AND (candidate->>'chineseSimplified' = '' OR strpos(normalize(source.cn_s, NFC), normalize(candidate->>'chineseSimplified', NFC)) > 0)
      AND (candidate->>'chineseTraditional' = '' OR strpos(normalize(source.cn_t, NFC), normalize(candidate->>'chineseTraditional', NFC)) > 0)
    LIMIT 1 FOR SHARE OF unit, source, approved;
    IF valid_source IS NOT TRUE THEN
      skipped_keys := skipped_keys || jsonb_build_array(candidate->>'key');
      CONTINUE;
    END IF;
    IF EXISTS (
      SELECT 1 FROM (
        SELECT entry.id, entry.metadata FROM editor_dictionary_entries entry JOIN editor_dictionaries dictionary ON dictionary.id = entry.dictionary_id
          WHERE dictionary.is_team AND dictionary.visibility = 'public'
        UNION ALL
        SELECT proposal.id, proposal.metadata FROM editor_dictionary_proposals proposal JOIN editor_dictionaries dictionary ON dictionary.id = proposal.dictionary_id
          WHERE dictionary.is_team AND dictionary.visibility = 'public' AND proposal.status IN ('pending', 'held')
      ) current_rule
      WHERE current_rule.id = (candidate->>'id')::uuid OR (current_rule.metadata->>'kind' = 'term' AND (
        (candidate->>'japanese' <> '' AND normalize(current_rule.metadata->>'japanese', NFC) = normalize(candidate->>'japanese', NFC))
        OR (candidate->>'chineseSimplified' <> '' AND normalize(current_rule.metadata->>'chineseSimplified', NFC) = normalize(candidate->>'chineseSimplified', NFC))
        OR (candidate->>'chineseTraditional' <> '' AND normalize(current_rule.metadata->>'chineseTraditional', NFC) = normalize(candidate->>'chineseTraditional', NFC))
      ))
    ) THEN
      existing_count := existing_count + 1;
      CONTINUE;
    END IF;
    IF target_dictionary IS NULL THEN
      IF EXISTS (SELECT 1 FROM editor_dictionaries WHERE id = '${BASE_GLOSSARY_ID}'::uuid) THEN
        RAISE EXCEPTION 'Base glossary id belongs to another dictionary; existing data was preserved';
      END IF;
      target_dictionary := '${BASE_GLOSSARY_ID}'::uuid;
      INSERT INTO editor_dictionaries (id, owner_id, name, description, visibility, is_team)
        VALUES (target_dictionary, 'bot', '공통 번역 기준', '기존 한국어 번역에서 정리한 기초 용어', 'public', true);
    END IF;
    INSERT INTO editor_dictionary_entries (id, dictionary_id, source_text, translation, note, metadata, created_by)
      VALUES ((candidate->>'id')::uuid, target_dictionary,
        COALESCE(NULLIF(candidate->>'japanese', ''), NULLIF(candidate->>'chineseSimplified', ''), candidate->>'chineseTraditional'),
        candidate->>'translation', candidate->>'note', defaults || jsonb_build_object(
          'japanese', candidate->>'japanese', 'chineseSimplified', candidate->>'chineseSimplified',
          'chineseTraditional', candidate->>'chineseTraditional', 'evidenceKey', candidate->>'key'
        ), 'bot');
    added_count := added_count + 1;
  END LOOP;
  IF added_count > 0 THEN
    UPDATE editor_dictionaries SET updated_at = now() WHERE id = target_dictionary;
  END IF;
  PERFORM set_config('astral.base_glossary_result', jsonb_build_object(
    'dictionaryId', target_dictionary, 'added', added_count, 'existing', existing_count, 'skipped', skipped_keys
  )::text, true);
  RAISE NOTICE 'Base glossary: added %, existing %, skipped evidence %', added_count, existing_count, jsonb_array_length(skipped_keys);
END
$base_glossary$;
`
}
